#!/usr/bin/env node

/**
 * RadioOS Supabase Setup Helper
 *
 * This script helps you set up Supabase for RadioOS.
 * Run it with: node scripts/setup-supabase.js
 */

const fs = require("fs");
const path = require("path");
const readline = require("readline");

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
});

const question = (query) =>
  new Promise((resolve) => rl.question(query, resolve));

async function main() {
  console.log("\n🎛️  RadioOS Supabase Setup\n");
  console.log("This script will help you configure Supabase for RadioOS.\n");
  console.log("Prerequisites:");
  console.log("1. A Supabase account (https://supabase.com)");
  console.log("2. A new project created in Supabase\n");

  // Check if .env.local already exists
  const envPath = path.join(process.cwd(), ".env.local");
  if (fs.existsSync(envPath)) {
    const overwrite = await question(
      "⚠️  .env.local already exists. Overwrite? (y/N): "
    );
    if (overwrite.toLowerCase() !== "y") {
      console.log("Setup cancelled.");
      process.exit(0);
    }
  }

  console.log("\n📋 Please enter your Supabase credentials:\n");
  console.log("You can find these in: Supabase Dashboard → Project Settings → API\n");

  const supabaseUrl = await question("Supabase Project URL: ");
  const anonKey = await question("Supabase Anon Key: ");
  const serviceKey = await question("Supabase Service Role Key: ");
  const dbPassword = await question("Database Password: ");

  // Extract project ID from URL
  const projectId = supabaseUrl.match(/https:\/\/([^.]+)\.supabase\.co/)?.[1];

  if (!projectId) {
    console.error("❌ Invalid Supabase URL format");
    process.exit(1);
  }

  const envContent = `# ============================================
# RadioOS Environment Variables
# Generated by setup-supabase.js
# ============================================

# Supabase
NEXT_PUBLIC_SUPABASE_URL=${supabaseUrl}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}
SUPABASE_SERVICE_ROLE_KEY=${serviceKey}

# Database
DATABASE_URL=postgresql://postgres:${dbPassword}@db.${projectId}.supabase.co:5432/postgres
DIRECT_URL=postgresql://postgres:${dbPassword}@db.${projectId}.supabase.co:5432/postgres

# App
NEXT_PUBLIC_APP_URL=http://localhost:3000
NEXT_PUBLIC_APP_NAME=RadioOS
NEXT_PUBLIC_DEFAULT_BITRATE=128
`;

  fs.writeFileSync(envPath, envContent);

  console.log("\n✅ .env.local created successfully!\n");

  // Display next steps
  console.log("📝 Next Steps:\n");
  console.log("1. Go to your Supabase Dashboard");
  console.log("2. Navigate to SQL Editor");
  console.log("3. Run the migration files in order:");
  console.log("   - supabase/migrations/001_initial_schema.sql");
  console.log("   - supabase/rls_policies.sql");
  console.log("   - (Optional) supabase/seed.sql\n");
  console.log("4. Start the development server:");
  console.log("   npm run dev\n");
  console.log("5. Visit http://localhost:3000 and register!\n");

  console.log("📚 For more details, see SUPABASE_SETUP.md\n");

  rl.close();
}

main().catch(console.error);
